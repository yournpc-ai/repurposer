"""Canonical storyboard read face (VIDEO_PROJECT §2.3, §3.3, §10.3).

``storyboard_payload`` is generated by the server from a SAVED version —
deterministically, from content alone. Tools receive the complete facts so
the LLM can write a grounded Markdown creative overview; the same DTO backs
the version reference and carries the stable ids (scene / clip / animation)
that a revision names. The UI does not re-render this as a technical table.

Columns (§3.3): scene number / time / frames, the visual description (or
the honest fact fallback), the exact on-screen text, the saved narration
and voice, and the source/audio facts. Pending Speech is reviewed as text;
only authorized production resolves its actual audio and cue timings.

Pure function over typed content — safe as the UI's parallel-build fixture
source.
"""

from __future__ import annotations

from typing import Any
from uuid import UUID

from app.editing.schemas import (
    AudioObject,
    Clip,
    CompositionContent,
    GeneratorObject,
    ImageObject,
    ShapeObject,
    SpeechObject,
    TextObject,
    VideoObject,
    WebObject,
)
from app.editing.timing import SOURCE_TIMEBASE, ticks_to_frames


def _kf_summary(kf: Any, timebase: int, fps_num: int, fps_den: int) -> dict[str, Any]:
    return {
        "at_seconds": kf.at / timebase,
        "at_frame": ticks_to_frames(kf.at, timebase, fps_num, fps_den),
        "value": list(kf.value) if isinstance(kf.value, tuple) else kf.value,
        "easing": kf.easing.kind,
    }


def _clip_summary(
    clip: Clip,
    content: CompositionContent,
    *,
    track_role: str,
    view_facts: dict[tuple[UUID, str], dict[str, Any]],
) -> dict[str, Any]:
    settings = content.settings
    timebase = settings.timebase
    fps_num, fps_den = settings.fps.num, settings.fps.den
    summary: dict[str, Any] = {
        "clip_id": clip.clip_id,
        "linked_group_id": clip.linked_group_id,
        "object_id": clip.object.object_id,
        "object_kind": clip.object.kind,
        "track_role": track_role,
        "range_ticks": {"start": clip.range.start, "end": clip.range.end},
        "range_seconds": {
            "start": clip.range.start / timebase,
            "end": clip.range.end / timebase,
        },
        "range_frames": {
            "start": ticks_to_frames(clip.range.start, timebase, fps_num, fps_den),
            "end": ticks_to_frames(clip.range.end, timebase, fps_num, fps_den),
        },
        "animations": [
            {
                "animation_id": anim.animation_id,
                "property": anim.property,
                "text_part": anim.text_part.kind if anim.text_part is not None else None,
                "keyframes": [
                    _kf_summary(kf, timebase, fps_num, fps_den) for kf in anim.keyframes
                ],
            }
            for anim in clip.animations
        ],
    }
    obj = clip.object
    if clip.source is not None:
        summary["snapshot_id"] = str(clip.source.snapshot_id)
        if clip.source.source_range is not None:
            summary["source_range_seconds"] = {
                "start": clip.source.source_range.start / SOURCE_TIMEBASE,
                "end": clip.source.source_range.end / SOURCE_TIMEBASE,
            }
    if isinstance(obj, TextObject):
        summary["text"] = obj.text
        summary["style"] = {
            "font_size": obj.style.font_size,
            "color": obj.style.color,
            "background": obj.style.background,
            "weight": obj.style.weight,
            "align": obj.style.align,
        }
        summary["layout"] = obj.layout.model_dump(mode="json")
        if obj.caption is not None:
            summary["caption"] = obj.caption.model_dump(mode="json")
    elif isinstance(obj, ShapeObject):
        summary["shape"] = obj.shape
        summary["fill"] = obj.fill
        summary["stroke"] = obj.stroke
        summary["stroke_width"] = obj.stroke_width
        summary["corner_radius"] = obj.corner_radius
        summary["path"] = obj.path
        summary["layout"] = obj.layout.model_dump(mode="json")
        summary["opacity"] = obj.opacity
    elif isinstance(obj, WebObject):
        view = view_facts.get((clip.source.snapshot_id, obj.view_id)) if clip.source else None
        summary["view_id"] = obj.view_id
        if view is not None:
            summary["view"] = view
    elif isinstance(obj, ImageObject):
        summary["layout"] = obj.layout.model_dump(mode="json")
    elif isinstance(obj, VideoObject):
        summary["layout"] = obj.layout.model_dump(mode="json")
        summary["fit"] = obj.fit
        summary["gain_db"] = obj.gain_db
        summary["muted"] = obj.muted
    elif isinstance(obj, GeneratorObject):
        summary["runtime"] = obj.runtime
        summary["code"] = obj.code
        summary["prompt"] = obj.prompt
        summary["provider"] = obj.provider
        summary["model"] = obj.model
        summary["parameters"] = obj.parameters
        summary["output"] = obj.output.model_dump(mode="json")
        summary["program_digest"] = obj.program_digest()
        summary["layout"] = obj.layout.model_dump(mode="json")
        summary["fit"] = obj.fit
        summary["opacity"] = obj.opacity
    elif isinstance(obj, SpeechObject):
        summary["text"] = obj.text
        summary["provider"] = obj.provider
        summary["model"] = obj.model
        summary["voice_id"] = obj.voice_id
        summary["language"] = obj.language
        summary["gain_db"] = obj.gain_db
        summary["role"] = track_role
    elif isinstance(obj, AudioObject):
        summary["gain_db"] = obj.gain_db
        summary["role"] = track_role
    return summary


def storyboard_payload(
    content: CompositionContent,
    *,
    composition_id: UUID,
    version_id: UUID,
    version: int,
    content_digest: str,
    source_facts: dict[UUID, dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """The canonical per-scene readout of a saved version.

    ``source_facts`` (snapshot rows as plain facts — the read seat resolves
    them) supplies the material column: kind, canonical URL, per-view
    headings. Absent facts degrade to ids, never to invention.
    """
    source_facts = source_facts or {}
    beat_grids = {key: (facts.get("meta") or {}).get("beat_grid") or {}
                  for key, facts in source_facts.items()}
    settings = content.settings
    timebase = settings.timebase
    fps_num, fps_den = settings.fps.num, settings.fps.den

    view_facts: dict[tuple[UUID, str], dict[str, Any]] = {}
    for snapshot_id, facts in source_facts.items():
        for view in (facts.get("meta") or {}).get("views") or []:
            view_facts[(snapshot_id, str(view.get("view_id")))] = {
                "view_id": str(view.get("view_id")),
                "heading": str(view.get("heading") or ""),
                "width": view.get("width"),
                "height": view.get("height"),
            }

    clip_tracks: dict[str, str] = {}
    for track in content.timeline.tracks:
        for clip in track.clips:
            clip_tracks[clip.clip_id] = track.role

    all_clips = [c for t in content.timeline.tracks for c in t.clips]
    scenes = []
    for index, scene in enumerate(content.scenes):
        scene_clips = [c for c in all_clips if c.scene_id == scene.scene_id]
        by_id = {c.clip_id: c for c in scene_clips}
        speech = [
            by_id[ref].object
            for ref in scene.speech_clip_ids
            if ref in by_id and isinstance(by_id[ref].object, SpeechObject)
        ]
        scene_payload: dict[str, Any] = {
            "scene_id": scene.scene_id,
            "number": index + 1,
            "range_seconds": {
                "start": scene.range.start / timebase,
                "end": scene.range.end / timebase,
            },
            "range_frames": {
                "start": ticks_to_frames(scene.range.start, timebase, fps_num, fps_den),
                "end": ticks_to_frames(scene.range.end, timebase, fps_num, fps_den),
            },
            "intent": scene.intent,
            "visual_description": scene.visual_description,
            "narration": "\n".join(obj.text for obj in speech) if speech else None,
            "clips": [
                _clip_summary(
                    c, content, track_role=clip_tracks[c.clip_id], view_facts=view_facts
                )
                for c in scene_clips
            ],
        }
        if speech:
            scene_payload["narration_voices"] = [
                {
                    "provider": obj.provider,
                    "model": obj.model,
                    "voice_id": obj.voice_id,
                    "language": obj.language,
                }
                for obj in speech
            ]
        scenes.append(scene_payload)
    return {
        "composition_id": str(composition_id),
        "composition_version_id": str(version_id),
        "version": version,
        "content_digest": content_digest,
        "settings": {
            "width": settings.width,
            "height": settings.height,
            "fps": fps_num / fps_den,
            "background": settings.background,
        },
        "duration_seconds": (
            max((c.range.end for c in all_clips), default=0) / timebase
        ),
        "sources": [
            {
                "snapshot_id": str(binding.snapshot_id),
                "beat_grid": {
                    "available": bool(beat_grids.get(binding.snapshot_id, {}).get("beats")),
                    "bpm": beat_grids.get(binding.snapshot_id, {}).get("bpm"),
                },
                "kind": (source_facts.get(binding.snapshot_id) or {}).get("kind"),
                "url": (
                    (source_facts.get(binding.snapshot_id) or {}).get("meta") or {}
                ).get("canonical_url"),
            }
            for binding in content.sources
        ],
        "scenes": scenes,
        "transitions": [{**transition.model_dump(mode="json"),
                         "duration_seconds": transition.duration / content.settings.timebase}
                        for transition in content.timeline.transitions],
        "unassigned_clips": [
            _clip_summary(c, content, track_role=clip_tracks[c.clip_id], view_facts=view_facts)
            for c in all_clips
            if c.scene_id is None
        ],
    }
