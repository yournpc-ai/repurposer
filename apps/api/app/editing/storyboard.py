"""Canonical storyboard read face (VIDEO_PROJECT §2.3, §10.3).

``storyboard_payload`` is generated by the server from a SAVED version —
deterministically, from content alone. Chat presents this payload (the LLM
never re-transcribes a storyboard table). First-slice scope: scenes with
their clips' factual projection (kind, output window, text preview), plus
the version identity. Tracks without scene attribution surface under
``scene_id: null``.

Pure function over typed content — safe as the UI's parallel-build fixture
source.
"""

from __future__ import annotations

from typing import Any
from uuid import UUID

from app.editing.schemas import Clip, CompositionContent, TextObject


def _clip_summary(clip: Clip, content: CompositionContent) -> dict[str, Any]:
    timebase = content.settings.timebase
    summary: dict[str, Any] = {
        "clip_id": clip.clip_id,
        "object_kind": clip.object.kind,
        "range_ticks": {"start": clip.range.start, "end": clip.range.end},
        "range_seconds": {
            "start": float(clip.range.start) / timebase,
            "end": float(clip.range.end) / timebase,
        },
        "has_source": clip.source is not None,
    }
    if isinstance(clip.object, TextObject):
        summary["text"] = clip.object.text
    return summary


def storyboard_payload(
    content: CompositionContent,
    *,
    composition_id: UUID,
    version_id: UUID,
    version: int,
    content_digest: str,
) -> dict[str, Any]:
    """The canonical per-scene readout of a saved version."""
    clips = [c for t in content.timeline.tracks for c in t.clips]
    scenes = []
    for scene in content.scenes:
        scenes.append(
            {
                "scene_id": scene.scene_id,
                "range_seconds": {
                    "start": scene.range.start / content.settings.timebase,
                    "end": scene.range.end / content.settings.timebase,
                },
                "intent": scene.intent,
                "visual_description": scene.visual_description,
                "clips": [
                    _clip_summary(c, content)
                    for c in clips
                    if c.scene_id == scene.scene_id
                ],
            }
        )
    return {
        "composition_id": str(composition_id),
        "composition_version_id": str(version_id),
        "version": version,
        "content_digest": content_digest,
        "settings": {
            "width": content.settings.width,
            "height": content.settings.height,
            "fps": content.settings.fps.num / content.settings.fps.den,
        },
        "scenes": scenes,
        "unassigned_clips": [
            _clip_summary(c, content) for c in clips if c.scene_id is None
        ],
    }
