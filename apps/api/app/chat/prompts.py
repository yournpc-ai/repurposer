        "is copy-writers alone and no media is attached, the echo must "
        "ALSO tell the user, briefly and warmly: this is a draft from "
        "your prompt plus your persona style — no source material is being "
        "used. If you have notes or a draft to bring in, paste it (or "
        "attach a file) and the next turn will pull from it. (Avoid a "
        "defensive tone — the draft is real, the disclaimer is for "
        "informed consent.)\n"
        "- tasks: array of tasks — the tool chain to run, one object per "
        "piece of work, in execution order: "
        '{"tool": "<name>", "params": {...}}.\n'
